package agent

import (
	"regexp"
	"strings"
)

// Проверки ДО модели: такие сообщения вообще не уходят во внешний LLM.

// BR-61, BR-72: чувствительные ПДн и финансы не обрабатываются и не передаются в LLM.
// Блокируются сами данные, а не слова: «в какой витрине банковские транзакции?» или «где реквизиты юрлица
// для договора?» — рабочие вопросы аналитика (тест TestPIINotWorkTopics).
var piiPatterns = []*regexp.Regexp{
	regexp.MustCompile(`\b\d{4}[\s-]?\d{4}[\s-]?\d{4}[\s-]?\d{4}\b`), // номер карты
	regexp.MustCompile(`\b\d{2}\s?\d{2}\s\d{6}\b`),                   // серия и номер паспорта: «45 10 123456», «4510 123456»
	regexp.MustCompile(`\b\d{3}-\d{3}-\d{3}\s?\d{2}\b`),              // СНИЛС
}

// sharesPII — человек делится своими данными или просит их сохранить, даже без цифр:
// «вот мой паспорт», «запиши мои реквизиты», «у меня диагноз…», «паспорт: 4510…».
var sharesPII = regexp.MustCompile(`(?i)(мо[йиеяю]|вот|запиши|сохрани|внеси|запомни)[^.?!\n]{0,20}(паспорт|снилс|реквизит|номер карты|номер счёта|номер счета|банковск[а-я]* карт|диагноз)` +
	`|(паспорт|снилс|номер карты|сч[её]т)[а-я]*[^.?!\n\d]{0,12}\d{6}|у меня[^.?!\n]{0,15}диагноз`)

func luhn(digits string) bool {
	sum, double := 0, false
	for i := len(digits) - 1; i >= 0; i-- {
		d := int(digits[i] - '0')
		if double {
			if d *= 2; d > 9 {
				d -= 9
			}
		}
		sum, double = sum+d, !double
	}
	return sum%10 == 0
}

func onlyDigits(s string) string {
	return strings.Map(func(r rune) rune {
		if r >= '0' && r <= '9' {
			return r
		}
		return -1
	}, s)
}

// BR-60: оценка самого стажёра, выход в штат, зарплата, повышение, увольнение, конфликты с людьми — решают люди.
// Только про человека, а не про работу: «оценка эффекта A/B», «повышение конверсии», «конфликт мерджа» —
// рабочие вопросы аналитика, их отвечает агент (тест TestBoundaryNotWorkTopics).
var boundaryPattern = regexp.MustCompile(`(?i)` + strings.Join([]string{
	`в штат`, `(мне|мой|получу|дадут|сделают|будет ли)[а-я ]{0,10}оффер`, `оффер[а-я]* (мне|после стажировк)`,
	`меня оценива`, `оценива[а-я]* меня`, `(мо[яюей]|у меня[а-я ]{0,12}) оценк`, `оценк[а-я]* за стажировк`, `оценк[а-я]* (меня|моей работы|стаж[её]р)`, `как я справляюсь`,
	`(мо[яюей]|у меня|какая|сколько|когда|будет)[а-я ]{0,15}(зарплат|оклад)`, `(зарплат|оклад)[а-я]* (у |после |на )?стаж`, `сколько (получа|плат)`,
	`(меня|мне) (повыс|уволя|уволят)`, `повыс[а-я]* (ли )?меня`, `повышени[ея] (в должности|грейда|до )`, `уволят`, `увольн[а-я]* меня`,
	`конфликт[а-я]* с (коллег|руковод|бадди|наставник|командой)`, `поругал`, `поссорил`, `не ладим`, `обижа`,
}, "|"))

const (
	piiAnswer = "Такие данные я не обрабатываю и никуда не сохраняю. Паспортные и банковские данные вноси только в HR-сервисе — " +
		"там они защищены. Если нужна помощь с заявкой, напиши, что именно оформить, без самих данных."
	boundaryAnswer = "Это решают люди, а не я. Лучше обсудить с бадди или руководителем — могу подготовить вопрос, " +
		"а отправишь его ты."
)

func containsPII(text string) bool {
	// 16 цифр — карта, только если проходит контрольную сумму: номер заказа или ID события — не карта.
	for _, m := range piiPatterns[0].FindAllString(text, -1) {
		if luhn(onlyDigits(m)) {
			return true
		}
	}
	return piiPatterns[1].MatchString(text) || piiPatterns[2].MatchString(text) || sharesPII.MatchString(text)
}

// maskOnly — что ещё прячем при сохранении (история чата, журнал), хотя в модель это не блокируется:
// телефон, почта, секреты и токены (BR-72).
var maskOnly = []*regexp.Regexp{
	regexp.MustCompile(`(?:\+7|\b8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]?\d{2}[\s-]?\d{2}\b`), // телефон
	regexp.MustCompile(`[\w.+-]+@[\w-]+\.[\w.-]+`),                                    // почта
	regexp.MustCompile(`\b(?:sk|pk|ghp|xox[bp])[-_][A-Za-z0-9_-]{12,}\b`),             // ключи API
	regexp.MustCompile(`(?i)(парол[ья]|password|token|токен)\s*[:=]\s*\S+`),           // «пароль: …»
}

// MaskPII — перед сохранением: история чата, журнал событий (BR-72). Номера карт, паспорта, СНИЛС,
// телефоны, почта и секреты заменяются на «***».
func MaskPII(text string) string {
	for _, re := range append(append([]*regexp.Regexp{}, piiPatterns[:3]...), maskOnly...) {
		text = re.ReplaceAllString(text, "***")
	}
	return text
}

// guard возвращает готовый ответ, если сообщение нельзя отправлять в модель. people — к кому идти
// с вопросом о границах (BR-60): стажёру называем бадди и руководителя по имени, а не «кого-нибудь».
func guard(text, people string) (string, bool) {
	switch {
	case containsPII(text):
		return piiAnswer, true
	case boundaryPattern.MatchString(strings.ToLower(text)):
		if people != "" {
			return "Это решают люди, а не я. Лучше обсудить лично: " + people + ". Могу подготовить вопрос, а отправишь его ты.", true
		}
		return boundaryAnswer, true
	}
	return "", false
}
